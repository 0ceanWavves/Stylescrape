exports.handler = async function(event, context) {
  // Log function invocation with context ID
  logInfo(`Download function invoked with ID: ${context.awsRequestId || 'local'}`, {
    path: event.path,
    method: event.httpMethod,
    headers: event.headers,
    queryParams: event.queryStringParameters
  });
  
  // Handle preflight CORS request
  if (event.httpMethod === 'OPTIONS') {
    return handleOptions();
  }
  
  try {
    // Only allow GET method
    if (event.httpMethod !== 'GET') {
      logInfo(`Method not allowed: ${event.httpMethod}`);
      return {
        statusCode: 405,
        headers: handleCors({ 'Content-Type': 'application/json' }),
        body: JSON.stringify({ 
          success: false,
          error: 'Method not allowed',
          details: 'Only GET requests are supported',
          debug: {
            receivedMethod: event.httpMethod,
            timestamp: new Date().toISOString()
          }
        })
      };
    }
    
    // Get domain from query parameter
    const { domain, analysis } = event.queryStringParameters || {};
    if (!domain) {
      logInfo('Missing domain parameter in request');
      return {
        statusCode: 400,
        headers: handleCors({ 'Content-Type': 'application/json' }),
        body: JSON.stringify({ 
          success: false, 
          error: 'Missing parameter',
          details: 'Domain parameter is required',
          debug: {
            receivedParams: Object.keys(event.queryStringParameters || {}),
            timestamp: new Date().toISOString()
          }
        })
      };
    }
    
    logInfo(`Processing download request for domain: ${domain}`);
    
    // Parse analysis data if provided
    let analysisData = null;
    if (analysis) {
      try {
        analysisData = JSON.parse(decodeURIComponent(analysis));
        logInfo('Analysis data included in download', { analysisData });
      } catch (e) {
        logError('Error parsing analysis data', e);
      }
    }
    
    // Generate ZIP file in base64
    const zipBase64 = generateComprehensiveZip(domain, analysisData);
    
    // Convert base64 to buffer
    const zipBuffer = Buffer.from(zipBase64, 'base64');
    
    logInfo('Download prepared successfully', { 
      domain,
      analysisIncluded: !!analysisData,
      zipSize: zipBuffer.length
    });
    
    // Return the ZIP file
    return {
      statusCode: 200,
      headers: handleCors({
        'Content-Disposition': `attachment; filename="${domain}-clone.zip"`
      }),
      body: zipBase64,
      isBase64Encoded: true
    };
    
  } catch (error) {
    logError('Unexpected error in function', error);
    
    // Return error response with detailed debugging info
    return {
      statusCode: 500,
      headers: handleCors({ 'Content-Type': 'application/json' }),
      body: JSON.stringify({
        success: false,
        error: 'Server error',
        details: error.message,
        debug: {
          functionId: context.awsRequestId || 'local',
          errorName: error.name,
          errorStack: process.env.NODE_ENV === 'development' ? error.stack : undefined,
          timestamp: new Date().toISOString()
        }
      })
    };
  }
}; 